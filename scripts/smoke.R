library(ggplot2)
library(dplyr)
library(testthat)
stopifnot(identical(dplyr::summarise(data.frame(x = 1:3), n = sum(x))$n, 6L))
p <- ggplot(data.frame(x = 1:3, y = c(1, 3, 2)), aes(x, y)) + geom_line()
f <- tempfile(fileext = ".png")
ragg::agg_png(f)
print(p)
dev.off()
stopifnot(file.info(f)$size > 0)
f <- tempfile(fileext = ".svg")
svglite::svglite(f)
print(p)
dev.off()
stopifnot(file.info(f)$size > 0)
cat(R.version.string, "\nData manipulation and PNG/SVG plotting passed.\n")
